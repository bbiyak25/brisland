package chap02;

public class chap0202_VariableTypes {
    public static void main(String[] args) {
        int var1 = 0b01001;         //2진수
        int var2 = 0206;            //8진수
        int var3 = 309;             //10진수
        int var4 = 0xBB;            //16진수

        long var5 = 2000000000L;    //long 변수
        char var6 = 'A';            //char 변수
        String var7 = "필승의309";  //String 클래스, 클래스라서 대문자 String

        double var8 = 0.25;        //실수는 기본적으로 double
        float var9 = 0.26f;        //float는 f 붙혀야함
        
        boolean var10 = true;       //참거짓 변수



    }

}
